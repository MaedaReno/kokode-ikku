// 撮影ボタン、句の調子、自分で詠む流れと講評を確かめる
import { chromium } from "playwright-core";
import fs from "node:fs";
import path from "node:path";

const out = process.argv[2] ?? "e2e-out";
const base = process.env.BASE_URL ?? "http://localhost:8788";
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
const shot = (name, full = false) => page.screenshot({ path: path.join(out, `${name}.png`), fullPage: full });
await page.addInitScript(() => sessionStorage.setItem("splashSeen", "1"));
await page.goto(base);
await page.waitForTimeout(800);
await shot("01-home");
console.log("camera inputs:", await page.evaluate(() => [...document.querySelectorAll("input[capture]")].map((i) => i.accept + ":" + i.getAttribute("capture"))));

await page.evaluate(async () => {
  const c = document.createElement("canvas");
  c.width = 1080;
  c.height = 1350;
  const g = c.getContext("2d");
  const sky = g.createLinearGradient(0, 0, 0, 1000);
  sky.addColorStop(0, "#2b3a67");
  sky.addColorStop(1, "#f6c27a");
  g.fillStyle = sky;
  g.fillRect(0, 0, 1080, 1350);
  g.fillStyle = "#1c1612";
  for (let i = 0; i < 7; i++) g.fillRect(i * 160, 650 - ((i * 97) % 300), 120, 900);
  const blob = await new Promise((r) => c.toBlob(r, "image/jpeg", 0.9));
  const dt = new DataTransfer();
  dt.items.add(new File([blob], "t.jpg", { type: "image/jpeg" }));
  const input = document.querySelector('input[type="file"]:not([capture])');
  input.files = dt.files;
  input.dispatchEvent(new Event("change", { bubbles: true }));
});
await page.waitForSelector(".compose");
await page.waitForTimeout(900);
await page.getByRole("button", { name: "渋い" }).click();
await shot("02-ai-mode", true);

await page.getByRole("radio", { name: /自分で詠む/ }).click();
await page.waitForTimeout(300);
await page.getByLabel("上五").fill("秋の暮");
await page.getByLabel("中七").fill("缶の珈琲");
await page.waitForTimeout(600);
await shot("03-self-typing");
await page.getByLabel("下五").click();
await page.getByRole("button", { name: "ヒントをもらう" }).click();
await page.waitForSelector(".self .hint", { timeout: 20000 });
await page.getByLabel("下五").fill("ぬるく持つ");
await page.waitForTimeout(700);
await shot("04-self-done", true);
await page.getByRole("button", { name: "この句で仕上げる" }).click();
await page.waitForSelector(".result");
await page.waitForFunction(() => !document.querySelector(".stage.immersive"), null, { timeout: 30000 });
await page.waitForTimeout(600);
await page.getByRole("button", { name: /選者に講評/ }).click();
await page.waitForSelector(".critique", { timeout: 30000 });
await page.waitForTimeout(1300);
await page.locator(".critique").scrollIntoViewIfNeeded();
await shot("05-critique");
await page.getByRole("button", { name: "この案で書き直す" }).click();
await page.waitForTimeout(1000);
console.log("after revision:", await page.locator(".haiku-text").textContent());
console.log("errors:", errors);
await browser.close();
